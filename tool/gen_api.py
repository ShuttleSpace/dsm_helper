#!/usr/bin/env python3
"""从抓包 HAR 生成 dsm_api 的 Dart 封装（只补未实现的 API）。

用法:
    python3 tool/gen_api.py <har...> [--out lib/api/dsm_api.captured.g.dart]

流程: tool/har_dump.py 负责解析 -> 本脚本合并、跳过 lib/api 里已出现的
SYNO.* API、为其余每个 (api, method) 生成一个函数，写成一个 part 文件。

注意: 已实现的 API 字符串一旦在 lib/api 出现就整条跳过，避免重名/覆盖。
抓包里只覆盖首次加载会触发的 method（多为 list/get）；更深层操作可按需补抓。
"""
import sys, os, re, glob, json, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from har_dump import parse


def load_any(paths):
    """合并 .har 与 .json 规格（.json 由 har_dump --json 产出）。"""
    spec = collections.defaultdict(lambda: collections.defaultdict(set))
    for api, methods in parse([p for p in paths if p.endswith(".har")]).items():
        for k, v in methods.items():
            spec[api][k] |= set(v)
    for jp in [p for p in paths if p.endswith(".json")]:
        try:
            d = json.load(open(jp))
        except Exception as e:
            print("skip %s: %s" % (jp, e), file=sys.stderr)
            continue
        for api, items in d.items():
            for it in items:
                key = (it.get("method"), str(it.get("version")) if it.get("version") is not None else None)
                spec[api][key] |= set(it.get("params", []))
    return spec

# 批量包装器/鉴权等不生成
SKIP_APIS = {"SYNO.Entry.Request", "SYNO.API.Info", "SYNO.API.Auth"}


def pascal(tok):
    parts = re.split(r"[._]", tok)
    out = []
    for p in parts:
        if not p:
            continue
        if p.isupper():            # OAUTH -> Oauth
            out.append(p[0] + p[1:].lower())
        else:
            out.append(p[0].upper() + p[1:])
    return "".join(out)


def existing_apis():
    src = ""
    for f in glob.glob("lib/api/*.dart"):
        if f.endswith(".g.dart"):      # 跳过生成文件自身，否则会自我跳过
            continue
        src += open(f, errors="ignore").read()
    return set(re.findall(r"SYNO\.[A-Za-z0-9_.]+", src))


def gen(spec, out_path):
    have = existing_apis()
    # 合并同 api+method 的多版本：取最高 version，参数取并集
    merged = {}
    for api, methods in spec.items():
        for (method, ver), params in methods.items():
            if not method:
                continue
            key = (api, method)
            vnum = int(ver) if (ver and str(ver).isdigit()) else 0
            if key not in merged:
                merged[key] = {"version": vnum, "params": set(params)}
            else:
                merged[key]["version"] = max(merged[key]["version"], vnum)
                merged[key]["params"] |= set(params)

    lines = [
        "// GENERATED by tool/gen_api.py from captured HARs — 不要手改。",
        "// 抓包来源见 tool/captured_api.json / docs/API_CAPTURE.md。",
        "// ignore_for_file: non_constant_identifier_names",
        "part of 'dsm_api.dart';",
        "",
    ]
    count = 0
    skipped = []
    for api in sorted({k[0] for k in merged}):
        if api in SKIP_APIS or api in have:
            if api not in SKIP_APIS:
                skipped.append(api)
            continue
        fn = "dsm" + pascal(api[5:] if api.startswith("SYNO.") else api)
        for (a, method), info in sorted(
            [(k, v) for k, v in merged.items() if k[0] == api], key=lambda x: x[0][1]
        ):
            ver = info["version"] or 1
            # 参数名可能以下划线/非法字符开头（如 _dc），Dart 里改成合法局部名，data key 保持原名
            clean = []
            for p in sorted(info["params"]):
                dn = re.sub(r"[^A-Za-z0-9_]", "_", p).lstrip("_") or "p"
                if dn in {"res", "data", "extra"}:   # 避免遮蔽函数体局部变量
                    dn += "Param"
                clean.append((dn, p))
            fn_name = fn + pascal(method)
            sig = "".join("dynamic %s, " % dn for dn, _ in clean)
            if sig:
                sig = "{" + sig + "Map<String, dynamic>? extra}"
            else:
                sig = "{Map<String, dynamic>? extra}"
            body = [
                "/// %s.%s (v%d) — 抓包自动生成。" % (api, method, ver),
                "Future<dynamic> %s(%s) async {" % (fn_name, sig),
                "  final data = _dsmApiRequestData(api: '%s', method: '%s', version: %d);" % (api, method, ver),
            ]
            for dn, p in clean:
                body.append("  if (%s != null) data['%s'] = %s;" % (dn, p, dn))
            body += [
                "  if (extra != null) data.addAll(extra);",
                "  final res = await _httpGet(_entryCGI, queryParameters: data);",
                "  if (res['success'] != true) throw DSMException.fromMap(res);",
                "  return res['data'];",
                "}",
                "",
            ]
            lines += body
            count += 1

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    open(out_path, "w").write("\n".join(lines))
    print("生成 %d 个函数 -> %s" % (count, out_path))
    print("跳过已实现 API %d 个: %s" % (len(skipped), ", ".join(sorted(skipped))[:400]))


if __name__ == "__main__":
    args = sys.argv[1:]
    out = "lib/api/dsm_api.captured.g.dart"
    if "--out" in args:
        i = args.index("--out")
        out = args[i + 1]
        del args[i:i + 2]
    if not args:
        print(__doc__)
        sys.exit(1)
    gen(load_any(args), out)
